-- Брошенные оплаты — «Истёк», а не «Ошибка».
--
-- Фоновая задача раз в 5 минут закрывала неоплаченные задания старше
-- 30 минут статусом FAILED. Задание создаётся при нажатии «К оплате»,
-- поэтому каждый, кто увидел QR и не стал платить (передумал, вернулся
-- назад поменять настройки, ушёл), попадал в админку как «Ошибка».
-- Теперь такие задания получают EXPIRED; эта миграция исправляет историю.
--
-- Отбор безошибочный: payment_status = 'PENDING' ставится при создании
-- оплаты и меняется на PAID при оплате или на FAILED при отказе банка.
-- А киоск помечает задание FAILED только после оплаты (PAID). Значит,
-- FAILED + PENDING — это ровно задания, закрытые фоновой задачей.
UPDATE print_jobs
   SET status = 'EXPIRED'
 WHERE status = 'FAILED'
   AND payment_status = 'PENDING';
