-- Фактически печатаемые (и оплачиваемые) страницы задания.
--
-- page_count хранит ВСЕ страницы файла, но пользователь может выбрать часть
-- (напр. 9 из 10) — цена считается по выбранным. Без этой колонки метрика
-- «напечатано страниц» на дашборде завышала бы реальный объём печати.
ALTER TABLE print_jobs
    ADD COLUMN printed_pages INTEGER NOT NULL DEFAULT 0;

-- Backfill: для старых записей выбор страниц не сохранялся — считаем, что
-- печатался весь файл (так оно и было до появления выбора страниц).
UPDATE print_jobs SET printed_pages = page_count WHERE printed_pages = 0;
