-- Одноразовая ссылка для скачивания вместо четырёхзначного PIN.
--
-- Раньше /api/files/{pin}/download принимал сам PIN: 10 000 комбинаций,
-- то есть чужие сканы (паспорта, договоры) выкачивались перебором за
-- считаные минуты. Токен на 32 байта делает перебор бессмысленным.
--
-- PIN остаётся — но только для ввода на киоске, где он и задумывался.

ALTER TABLE files ADD COLUMN download_token VARCHAR(64);

-- Существующим файлам токен не проставляем: они живут 10 минут и
-- исчезнут сами. Обратная совместимость тут не нужна.

CREATE UNIQUE INDEX uniq_files_download_token
    ON files (download_token)
    WHERE download_token IS NOT NULL;
