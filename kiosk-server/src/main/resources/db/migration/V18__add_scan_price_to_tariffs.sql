-- Цена получения скана на телефон (сайт или Telegram), сом за страницу.
--
-- Раньше цена задавалась настройкой kiosk.scan-delivery.price-per-page-som
-- (по умолчанию 10) и менялась только правкой конфигурации с перезапуском
-- сервера. Теперь это часть тарифа, как цены ч/б и цветной печати: меняется
-- из админки, может отличаться по киоскам, а история сохраняется.
--
-- DEFAULT 10 переносит действовавшую цену: и в текущие строки тарифов, и
-- в исторические — по ним в прошлом и правда брали 10 сом.
ALTER TABLE tariffs
    ADD COLUMN scan_price_som INTEGER NOT NULL DEFAULT 10
        CHECK (scan_price_som >= 0);
