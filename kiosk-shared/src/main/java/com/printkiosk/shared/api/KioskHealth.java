package com.printkiosk.shared.api;

/** Цвет точки на карте сети (из ТЗ). */
public enum KioskHealth {
    OK,          // 🟢 всё работает
    WARNING,     // 🟡 заканчивается бумага/тонер, но киоск печатает
    DOWN,        // 🔴 не в сети, замятие, нет бумаги, сломан терминал
    MAINTENANCE  // ⚙️ переведён в режим обслуживания вручную
}
