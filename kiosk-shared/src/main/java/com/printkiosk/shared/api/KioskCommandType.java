package com.printkiosk.shared.api;

/** Что киоску сделать по команде из админки. */
public enum KioskCommandType {

    /**
     * Мягкая перезагрузка: перезапуск только приложения киоска.
     * Занимает секунды и чинит подавляющее большинство зависаний UI.
     * Рабочий выбор по умолчанию.
     */
    RESTART_APP,

    /**
     * Полная перезагрузка Windows. Нужна, когда проблема ниже приложения —
     * отвалился драйвер принтера, залип сканер, повисла сеть.
     * Занимает минуты и рискованнее: если машина не поднимется, придётся
     * ехать на точку.
     */
    REBOOT_OS
}
