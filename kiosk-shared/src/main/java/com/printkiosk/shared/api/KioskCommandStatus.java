package com.printkiosk.shared.api;

/** Жизненный цикл команды киоску. */
public enum KioskCommandStatus {

    /** Создана в админке, киоск её ещё не забрал. */
    PENDING,

    /** Отдана киоску в ответе на heartbeat, ждём подтверждения. */
    SENT,

    /**
     * Киоск принял команду и начал выполнять.
     *
     * <p>Именно «начал», а не «выполнил»: подтвердить перезагрузку ПОСЛЕ
     * перезагрузки некому — процесс к тому моменту уже убит. Поэтому киоск
     * отвечает до того, как дёрнуть shutdown.
     */
    DONE,

    /** Киоск отказался выполнять — например, был занят печатью. */
    FAILED,

    /**
     * Никто не забрал вовремя. Страховка от отложенного взрыва: киоск,
     * пролежавший офлайн сутки, не должен уйти в перезагрузку в момент,
     * когда наконец поднялся и к нему подошёл клиент.
     */
    EXPIRED,

    /** Оператор отменил до того, как киоск забрал команду. */
    CANCELLED
}
